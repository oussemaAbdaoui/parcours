"""Login page and public app (index.html), sandboxed end to end: tests/public_server.js serves the page and the real accounts handler
over an in-memory Postgres; a real browser signs up, chooses a path, reloads, signs out and in, and deletes the account.
Run: python tests/public_app_test.py
"""
import os
import subprocess
import tempfile
from playwright.sync_api import sync_playwright, expect

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
PORT = 4179
URL = f"http://localhost:{PORT}/"
server = subprocess.Popen(["node", os.path.join(ROOT, "tests", "public_server.js"), str(PORT)], stdout=subprocess.PIPE, text=True)
assert server.stdout.readline().strip() == "ready"
results = []
CV_HTML = """<h1>Amel Ben Salah</h1><p>Software engineer · Tunis · amel@example.tn</p>
<h2>Education</h2><p>Engineering degree in computer science (Diplôme d'ingénieur), ENICarthage, 2026</p>
<h2>Experience</h2><p>Data engineering intern, Acme, Tunis, February 2026 - July 2026. Built ETL pipelines in Python and SQL, Docker deployments.</p>
<h2>Skills</h2><p>Python, SQL, Docker, React, PostgreSQL, machine learning</p>
<h2>Languages</h2><p>Arabic: native. French: C1. English: B2.</p>"""


def check(name, fn):
    try:
        fn()
        results.append(True)
        print("PASS", name)
    except Exception as e:
        results.append(False)
        print("FAIL", name, "->", str(e).splitlines()[0][:200])


try:
    with sync_playwright() as p:
        b = p.chromium.launch()
        ctx = b.new_context(viewport={"width": 390, "height": 844})
        page = ctx.new_page()
        errors = []
        page.on("pageerror", lambda e: errors.append(str(e)))
        page.goto(URL)
        check("first visit shows the sign-up form", lambda: expect(page.locator("#authBtn")).to_have_text("Create my account"))
        page.fill("#name", "Amel Ben Salah")
        page.fill("#email", "amel@example.tn")
        page.fill("#password", "short")
        page.click("#authBtn")
        check("short password explained", lambda: expect(page.locator("#authMsg")).to_contain_text("at least 8"))
        page.fill("#password", "long-enough-1")
        page.click("#authBtn")
        check("sign-up opens the app on Profile", lambda: expect(page.locator("main h2")).to_have_text("Profile"))
        check("the four sections are there", lambda: expect(page.locator("nav.tabs a")).to_have_count(4))
        page.locator("input[value=study]").check()
        check("choosing a path opens Discover on master's", lambda: expect(page.locator("[data-tab=masters]")).to_have_attribute("aria-pressed", "true"))
        check("with real programmes listed", lambda: expect(page.locator("#discList .item h3").first).to_be_visible())
        page.goto(URL + "#profile")
        page.locator("input[value=work]").check()
        check("work path opens Discover on jobs", lambda: expect(page.locator("[data-tab=jobs]")).to_have_attribute("aria-pressed", "true"))
        check("jobs are listed", lambda: expect(page.locator("#discList .item")).to_have_count(3))
        page.click("[data-country=tn]")
        check("country filter", lambda: expect(page.locator("#discList .item h3")).to_have_text(["Développeur Full stack"]))
        page.locator("#discList [data-save]").first.click()
        check("save puts it in the tracker", lambda: expect(page.locator("#discList .saved-mark")).to_have_count(1))
        page.goto(URL + "#track")
        check("Track shows the saved offer", lambda: expect(page.locator("main .item h3")).to_have_text(["Développeur Full stack"]))
        page.select_option("main select[data-stage]", "applied")
        check("its stage can be moved to Applied", lambda: expect(page.locator("main .sec-head h3").first).to_contain_text("Applied"))
        page.goto(URL + "#profile")
        page.locator("input[value=study]").check()
        page.wait_for_timeout(300)
        page.reload()
        check("still signed in after reload", lambda: expect(page.locator("#app")).to_be_visible())
        page.goto(URL + "#profile")
        check("chosen path saved on the server", lambda: expect(page.locator("input[value=study]")).to_be_checked())
        page.goto(URL + "#home")
        check("home greets by first name", lambda: expect(page.locator("main h2")).to_have_text("Hello Amel"))
        check("home shows the latest picks for the path", lambda: expect(page.locator("#homeList .item").first).to_be_visible())
        check("home counts the applications", lambda: expect(page.locator(".stats .stat").nth(1).locator("b")).to_have_text("1"))
        # CV: a PDF made here (Chromium prints a CV page), read on the device, skills shown and matched on offers.
        cvdir = tempfile.mkdtemp()
        maker = b.new_page()
        maker.set_content(CV_HTML); cv_pdf = os.path.join(cvdir, "Amel_CV.pdf"); maker.pdf(path=cv_pdf)
        maker.set_content("<img src='data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk+M9QDwADhgGAWjR9awAAAABJRU5ErkJggg==' width=600 height=800>")
        scan_pdf = os.path.join(cvdir, "scan.pdf"); maker.pdf(path=scan_pdf); maker.close()
        page.goto(URL + "#home")
        check("home asks for the CV", lambda: expect(page.locator("main a[href='#profile']", has_text="Upload my CV")).to_be_visible())
        page.goto(URL + "#profile")
        page.set_input_files("#cvFile", scan_pdf)
        check("a scanned PDF is explained", lambda: expect(page.locator("#cvMsg")).to_contain_text("scan", timeout=20000))
        page.set_input_files("#cvFile", cv_pdf)
        check("the CV is read: skills shown", lambda: expect(page.locator("[data-rmskill=python]")).to_be_visible(timeout=20000))
        check("degree and languages read", lambda: expect(page.locator(".cv .rows")).to_contain_text("French"))
        check("file name kept", lambda: expect(page.locator(".cv-head")).to_contain_text("Amel_CV.pdf"))
        page.click("[data-rmskill=docker]")
        check("a wrong skill can be removed", lambda: expect(page.locator("[data-rmskill=docker]")).to_have_count(0))
        page.reload()
        check("the CV stays after reload (saved on the server)", lambda: expect(page.locator("[data-rmskill=python]")).to_be_visible())
        page.goto(URL + "#discover")
        page.click("[data-tab=jobs]")
        check("offers show the skills you have", lambda: expect(page.locator("#discList .have-line").first).to_contain_text("You have 2 of the 2"))
        check("matching skills are highlighted", lambda: expect(page.locator("#discList .skills span.have").first).to_be_visible())
        page.goto(URL + "#profile")
        page.click("#cvRemove")
        check("the CV can be deleted", lambda: expect(page.locator(".drop")).to_be_visible())
        check("the path is kept when the CV is deleted", lambda: expect(page.locator("input[value=study]")).to_be_checked())
        page.goto(URL + "#discover")
        page.click("[data-tab=alternance]")
        check("discover has an Alternance tab", lambda: expect(page.locator("#discList .item h3")).to_have_text(["Développeur web en alternance"]))
        page.goto(URL + "#track")
        page.reload()
        check("still tracked after reload (saved on the server)", lambda: expect(page.locator("main .item h3")).to_have_text(["Développeur Full stack"]))
        page.goto(URL + "#profile")
        page.click("#logout")
        check("sign out returns to Sign in", lambda: expect(page.locator("#authBtn")).to_have_text("Sign in"))
        page.reload()
        check("signed out for good after reload", lambda: expect(page.locator("#auth")).to_be_visible())
        page.click("#tabIn")
        page.fill("#email", "amel@example.tn")
        page.fill("#password", "wrong-password")
        page.click("#authBtn")
        check("wrong password explained", lambda: expect(page.locator("#authMsg")).to_have_text("Wrong email or password."))
        page.fill("#password", "long-enough-1")
        page.click("#authBtn")
        check("sign in works", lambda: expect(page.locator("main h2")).to_have_text("Hello Amel"))
        page.screenshot(path=os.path.join(os.environ.get("SHOTS", ROOT), "public-home.png"))
        page.goto(URL + "#profile")
        page.click("#delete")
        page.fill("#delPw", "long-enough-1")
        page.click("#delBtn")
        check("account deleted, back to sign-up", lambda: expect(page.locator("#authBtn")).to_have_text("Create my account"))
        page.click("#tabIn")
        page.fill("#email", "amel@example.tn")
        page.fill("#password", "long-enough-1")
        page.click("#authBtn")
        check("deleted account cannot sign in", lambda: expect(page.locator("#authMsg")).to_have_text("Wrong email or password."))
        check("no script errors", lambda: (_ for _ in ()).throw(AssertionError(errors)) if errors else None)

        # A public user who opens /admin is sent back to the public app.
        page.goto(URL)
        page.fill("#name", "Sami")
        page.fill("#email", "sami@example.tn")
        page.fill("#password", "long-enough-2")
        page.click("#authBtn")
        page.wait_for_url("**/#profile")
        page.goto(URL + "admin")
        page.wait_for_url("**/?admin=signin*")
        check("a public user is sent back from /admin", lambda: expect(page.locator("#app")).to_be_visible())
        check("and gets no admin button", lambda: expect(page.locator("a[href='/admin']")).to_have_count(0) if page.goto(URL + "#profile") or True else None)

        # The admin: same login page, lands in the admin app, signs out from there.
        admin = b.new_context(viewport={"width": 1280, "height": 800}).new_page()
        admin.on("pageerror", lambda e: errors.append("admin: " + str(e)))
        admin.goto(URL)
        admin.fill("#name", "Boss")
        admin.fill("#email", "boss@example.tn")
        admin.fill("#password", "admin-pass-123")
        admin.click("#authBtn")
        admin.wait_for_url("**/#profile")
        admin.request.get(URL + f"__test/promote?email=boss@example.tn")
        admin.goto(URL)
        check("the admin is taken to the admin app", lambda: admin.wait_for_url("**/admin*", timeout=8000))
        check("the admin app opens (its API accepts the admin pass)", lambda: expect(admin.locator(".side-foot [data-act=signout]")).to_be_visible())
        admin.wait_for_timeout(1500)
        check("the admin app stays open", lambda: (_ for _ in ()).throw(AssertionError(admin.url)) if "/admin" not in admin.url else None)
        admin.goto(URL + "?as=user")
        check("the admin can still see the public app (?as=user)", lambda: expect(admin.locator("#app")).to_be_visible())
        admin.goto(URL + "admin")
        admin.click(".side-foot [data-act=signout]")
        admin.wait_for_url(URL)
        check("sign-out from the admin app returns to the login page", lambda: expect(admin.locator("#auth")).to_be_visible())
        admin.goto(URL + "admin")
        check("signed out: /admin sends back to the login page", lambda: admin.wait_for_url("**/?admin=signin*", timeout=8000))
        check("no script errors in the admin app", lambda: (_ for _ in ()).throw(AssertionError(errors)) if errors else None)
        wide = b.new_page(viewport={"width": 1280, "height": 800})
        wide.goto(URL)
        wide.screenshot(path=os.path.join(os.environ.get("SHOTS", ROOT), "public-signup.png"))
        b.close()
finally:
    server.terminate()

print(f"\n{sum(results)}/{len(results)} passed")
raise SystemExit(0 if all(results) else 1)
